/**
 * Generates src/data/translations.js: a short Japanese gloss for each word the
 * game can score.
 *
 * Source is ejdict-hand (https://github.com/kujirahand/EJDict), released into
 * the public domain under CC0.  Its entries are full dictionary definitions --
 * `run` alone runs to fifty senses -- so this keeps the first sense only and
 * strips the notation down to something that fits in a pop-up.
 *
 * Clone ejdict-hand next to this repository (or pass its path as the first
 * argument) and run `npm run build:translations`.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORD_BLOCKS } from '../src/data/dictionary.js';
import { toGloss, baseForms, HAS_JAPANESE } from './gloss.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = process.argv[2] || '/home/user/kujirahand/ejdict/src';

if (!existsSync(SOURCE)) {
  console.error(`ejdict-hand source not found at ${SOURCE}`);
  console.error('Clone https://github.com/kujirahand/EJDict and pass its src/ path.');
  process.exit(1);
}

/**
 * word -> raw definition, as shipped by ejdict-hand.
 *
 * Two things about the source shape matter here:
 *  - a headword can list spelling variants, as in `color,colour`, and both
 *    need registering;
 *  - the headword must already be lower case in the file. Upper-case entries
 *    are abbreviations (`CAT` is clear air turbulence) and would otherwise
 *    shadow the everyday word.
 */
const raw = new Map();
for (const file of readdirSync(SOURCE)) {
  if (!file.endsWith('.txt')) continue;
  for (const line of readFileSync(join(SOURCE, file), 'utf8').split('\n')) {
    const tab = line.indexOf('\t');
    if (tab < 1) continue;
    const definition = line.slice(tab + 1);
    for (const variant of line.slice(0, tab).split(',')) {
      const headword = variant.trim();
      if (!/^[a-z]+$/.test(headword)) continue; // phrases, hyphens, abbreviations
      if (!raw.has(headword)) raw.set(headword, definition);
    }
  }
}

// `colour` is recorded as `=color`; follow those one hop so the cross-
// referenced spelling carries the real definition.
for (const [word, definition] of raw) {
  const reference = definition.match(/^=([a-z]+)\s*$/);
  if (!reference) continue;
  const target = raw.get(reference[1]);
  if (target && !/^=/.test(target)) raw.set(word, target);
  else raw.delete(word);
}

const glosses = new Map();
let direct = 0;
let derived = 0;

for (const [key, chunks] of Object.entries(WORD_BLOCKS)) {
  const length = Number(key);
  for (const chunk of chunks) {
    for (let i = 0; i + length <= chunk.length; i += length) {
      const word = chunk.slice(i, i + length);
      let gloss = raw.has(word) ? toGloss(raw.get(word)) : '';
      let viaBase = false;
      if (!gloss) {
        // Try the base forms in turn, and keep looking past any that only
        // cross-reference somewhere else.
        for (const base of baseForms(word)) {
          if (!raw.has(base)) continue;
          const candidate = toGloss(raw.get(base));
          if (!candidate || !HAS_JAPANESE.test(candidate)) continue;
          gloss = candidate;
          viaBase = true;
          break;
        }
      }
      if (!gloss || !HAS_JAPANESE.test(gloss)) continue;
      glosses.set(word, gloss);
      if (viaBase) derived += 1;
      else direct += 1;
    }
  }
}

const entries = [...glosses.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
const lines = [];
for (let i = 0; i < entries.length; i += 8) {
  const row = entries
    .slice(i, i + 8)
    .map(([word, gloss]) => `${word}\t${gloss}`)
    .join('\n');
  lines.push(`  ${JSON.stringify(row)},`);
}

const out = `// @generated by tools/build-translations.mjs -- do not edit by hand.
//
// Japanese glosses from ejdict-hand (https://github.com/kujirahand/EJDict),
// released into the public domain under CC0 1.0 by Kujira Hand. Definitions
// are reduced to their first sense so they fit in the game's pop-up.
//
// ${entries.length} entries. Each chunk below is a run of "word<TAB>gloss"
// lines; splitting on newline and then tab recovers the pairs.

export const TRANSLATION_CHUNKS = [
${lines.join('\n')}
];
`;

mkdirSync(resolve(ROOT, 'src/data'), { recursive: true });
writeFileSync(resolve(ROOT, 'src/data/translations.js'), out);

const total = [...Object.entries(WORD_BLOCKS)].reduce(
  (sum, [key, chunks]) => sum + chunks.reduce((n, chunk) => n + chunk.length / Number(key), 0),
  0,
);
console.log(`wrote src/data/translations.js`);
console.log(`  ${entries.length} of ${total} words covered (${((entries.length / total) * 100).toFixed(1)}%)`);
console.log(`  ${direct} direct, ${derived} via a base form`);
console.log(`  ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB`);
